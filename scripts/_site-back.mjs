import { chromium } from "playwright-core";
const browser = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true, args: ["--no-sandbox"] });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, serviceWorkers: "block" });
const page = await context.newPage();
await page.goto("http://127.0.0.1:4180/#/today", { waitUntil: "networkidle" });
await page.waitForTimeout(500);
console.log("app", await page.locator("h1").innerText());
await page.locator(".sidebar-brand").click();
await page.waitForTimeout(700);
console.log("url", page.url());
console.log("h1", await page.locator("h1").first().innerText());
console.log("site", await page.locator(".site").count(), "lang", await page.evaluate(() => document.documentElement.lang));
await browser.close();
